CLINICAL_DISCLAIMER = (
    "This prediction is generated by an automated clinical decision support system "
    "for informational and triage purposes only. It does not constitute a definitive medical diagnosis. "
    "Consult a licensed medical practitioner for clinical evaluation."
)


class PredictionListView(APIView):
    """
    GET /api/v1/predictions/
    Retrieves stored predictions for authenticated patient or authorized doctor.
    """
    permission_classes = [IsAuthenticatedUser]

    def get(self, request):
        user = request.user
        queryset = DiseasePrediction.objects.select_related("patient")

        if user.role == User.Roles.PATIENT:
            queryset = queryset.filter(patient=user)
        elif user.role == User.Roles.DOCTOR:
            patient_id = request.query_params.get("patient_id")
            if not patient_id:
                raise ValidationError("Doctors must supply 'patient_id' query param.")
            try:
                patient = User.objects.get(id=patient_id, role=User.Roles.PATIENT)
            except User.DoesNotExist:
                raise NotFound("Patient not found.")
            if not doctor_can_access_patient(user, patient):
                raise PermissionDenied("Unauthorized to view this patient's predictions.")
            queryset = queryset.filter(patient=patient)
        elif user.role == User.Roles.ADMIN or user.is_superuser:
            pass
        else:
            raise PermissionDenied("Access denied.")

        paginator = StandardResultsSetPagination()
        page = paginator.paginate_queryset(queryset, request)
        serializer = DiseasePredictionSerializer(page, many=True)
        return paginator.get_paginated_response(serializer.data)


class SymptomAnalysisListView(APIView):
    """
    GET /api/v1/predictions/symptoms/ — Lists symptom analysis history.
    POST /api/v1/predictions/symptoms/ — Maps input symptoms to canonical vocabulary & suggestions.
    """
    permission_classes = [IsAuthenticatedUser]

    def get(self, request):
        user = request.user
        queryset = SymptomAnalysis.objects.select_related("patient")

        if user.role == User.Roles.PATIENT:
            queryset = queryset.filter(patient=user)
        elif user.role == User.Roles.DOCTOR:
            patient_id = request.query_params.get("patient_id")
            if not patient_id:
                raise ValidationError("Doctors must supply 'patient_id' query param.")
            patient = User.objects.filter(id=patient_id, role=User.Roles.PATIENT).first()
            if not patient or not doctor_can_access_patient(user, patient):
                raise PermissionDenied("Unauthorized to view this patient's symptom analysis.")
            queryset = queryset.filter(patient=patient)
        elif user.role == User.Roles.ADMIN or user.is_superuser:
            pass
        else:
            raise PermissionDenied("Access denied.")

        paginator = StandardResultsSetPagination()
        page = paginator.paginate_queryset(queryset, request)
        serializer = SymptomAnalysisSerializer(page, many=True)
        return paginator.get_paginated_response(serializer.data)

    def post(self, request):
        raw_text = request.data.get("text", "")
        raw_symptoms = request.data.get("symptoms", [])

        input_data = raw_text if raw_text else raw_symptoms
        if not input_data:
            raise ValidationError("Either 'text' or 'symptoms' must be provided.")

        parsed = parse_symptoms(input_data)
        canonical = parsed["canonical_symptoms"]
        suggestions = suggest_related_symptoms(canonical)

        # Log analysis if requested for patient
        if request.user.role == User.Roles.PATIENT:
            SymptomAnalysis.objects.create(
                patient=request.user,
                symptoms_text=str(input_data),
                result={"canonical": canonical, "suggestions": suggestions},
            )

        return Response(
            {
                "canonical_symptoms": canonical,
                "feature_vector": parsed["feature_vector"],
                "unmapped_tokens": parsed["unmapped_tokens"],
                "suggested_symptoms": suggestions,
                "catalog": get_canonical_symptom_catalog(),
            },
            status=status.HTTP_200_OK,
        )


class DiseasePredictionCreateView(APIView):
    """
    POST /api/v1/predictions/disease/
    Executes disease classification inference + SHAP attribution.
    Logs prediction to database with patient permission checks.
    """
    permission_classes = [IsAuthenticatedUser]

    def post(self, request):
        user = request.user
        data = request.data

        # 1. Resolve Target Patient & Enforce Authority Boundaries
        if user.role == User.Roles.PATIENT:
            patient_id = data.get("patient_id")
            if patient_id and str(patient_id) != str(user.id):
                raise PermissionDenied("Patients can only request predictions for themselves.")
            target_patient = user
        elif user.role == User.Roles.DOCTOR:
            patient_id = data.get("patient_id")
            if not patient_id:
                raise ValidationError("Field 'patient_id' is required for doctors.")
            try:
                target_patient = User.objects.get(id=patient_id, role=User.Roles.PATIENT)
            except User.DoesNotExist:
                raise NotFound("Target patient does not exist.")
            if not doctor_can_access_patient(user, target_patient):
                raise PermissionDenied("Doctor does not have active clinical authorization for this patient.")
        elif user.role == User.Roles.ADMIN or user.is_superuser:
            patient_id = data.get("patient_id")
            if patient_id:
                try:
                    target_patient = User.objects.get(id=patient_id)
                except User.DoesNotExist:
                    raise NotFound("Target patient does not exist.")
            else:
                target_patient = user
        else:
            raise PermissionDenied("Access denied.")

        # 2. Extract Symptoms
        symptoms_input = data.get("symptoms") or data.get("text")
        if not symptoms_input:
            raise ValidationError("Field 'symptoms' (list or text) is required.")

        # 3. Parse Symptoms -> Vectorize
        parsed = parse_symptoms(symptoms_input)
        feature_vector = parsed["feature_vector"]

        # 4. Run Model Inference
        pred_result = predict_diseases(feature_vector)
        top = pred_result["top_prediction"]

        # 5. Generate SHAP Explanations
        shap_explanations = explain_prediction(feature_vector, top["disease"])

        # 6. Persist to Database History
        prediction_record = DiseasePrediction.objects.create(
            patient=target_patient,
            model_name=pred_result["model_metadata"]["model_name"],
            model_version=pred_result["model_metadata"]["model_version"],
            input_data={
                "symptoms_input": symptoms_input,
                "canonical_symptoms": parsed["canonical_symptoms"],
            },
            predicted_condition=top["disease"],
            confidence=top["probability"],
            explanation={
                "shap_attributions": shap_explanations,
                "ranked_diagnoses": pred_result["ranked_diagnoses"],
                "severity": top["severity"],
                "recommendation": top["recommendation"],
            },
        )

        log_audit_event(
            user=user,
            action=AuditLog.Actions.RECORD_CREATE,
            resource_type="DiseasePrediction",
            resource_id=prediction_record.id,
            request=request,
            metadata={
                "patient_id": target_patient.id,
                "condition": top["disease"],
                "confidence": top["probability"],
            },
        )

        response_payload = {
            "id": prediction_record.id,
            "patient_id": target_patient.id,
            "predicted_condition": top["disease"],
            "confidence": top["probability"],
            "severity": top["severity"],
            "recommendation": top["recommendation"],
            "canonical_symptoms": parsed["canonical_symptoms"],
            "shap_explanations": shap_explanations,
            "ranked_diagnoses": pred_result["ranked_diagnoses"],
            "model_metadata": pred_result["model_metadata"],
            "disclaimer": CLINICAL_DISCLAIMER,
            "created_at": prediction_record.created_at,
        }

        return Response(response_payload, status=status.HTTP_201_CREATED)
